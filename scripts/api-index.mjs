#!/usr/bin/env node
// API reference generator (FEAT-028.10): lists every symbol each package exports from its entry point, with its
// kind, source file and the first sentence of its doc comment, into docs/api.md. `--check` exits 1 when the file
// is out of date, so CI keeps the reference in step with the code.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, relative, sep } from 'node:path';
import { fileURLToPath, URL } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const ts = createRequire(join(root, 'package.json'))('typescript');
const packages = [
  ['@agentropy/core', 'packages/core', 'Types, schemas, errors, lifecycle tables and pure resolvers (no I/O)'],
  ['@agentropy/runtime', 'packages/runtime', 'Registries, task service, runtime, scheduler, providers and the local app facade'],
  ['@agentropy/store-sqlite', 'packages/store-sqlite', 'Store adapter on node:sqlite'],
  ['@agentropy/store-postgres', 'packages/store-postgres', 'Store adapter for PostgreSQL (driver-neutral)'],
  ['@agentropy/workflow-conductor', 'packages/workflow-conductor', 'WorkflowEngine adapter for Conductor'],
  ['@agentropy/testkit', 'packages/testkit', 'Offline fakes and reusable conformance suites'],
];

const program = ts.createProgram(
  packages.map(([, dir]) => join(root, dir, 'src/index.ts')),
  { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, strict: true, skipLibCheck: true },
);
const checker = program.getTypeChecker();

const kindOf = (decl) => {
  if (!decl) return 'value';
  if (ts.isInterfaceDeclaration(decl)) return 'interface';
  if (ts.isTypeAliasDeclaration(decl)) return 'type';
  if (ts.isClassDeclaration(decl)) return 'class';
  if (ts.isFunctionDeclaration(decl)) return 'function';
  if (ts.isEnumDeclaration(decl)) return 'enum';
  if (ts.isVariableDeclaration(decl)) return 'const';
  return 'value';
};

const summary = (sym) => {
  const text = ts.displayPartsToString(sym.getDocumentationComment(checker)).replace(/\s+/g, ' ').trim();
  if (!text) return '';
  const first = text.match(/^(.+?[.!?])(\s|$)/)?.[1] ?? text;
  return (first.length > 160 ? `${first.slice(0, 157)}…` : first).replace(/\|/g, '\\|');
};

let out = `# API reference\n\nGenerated by \`node scripts/api-index.mjs\` from each package's entry point; CI fails when it is out of date. Exported symbols are listed with their kind, source file and the first sentence of their doc comment. Nothing here is API-stable yet (pre-1.0); behaviour is specified by the [contracts](contracts/) and claimed only where a test exists. Start with the [quickstart](quickstart.md); version support is in the [compatibility matrix](compatibility.md).\n`;
let total = 0;
for (const [name, dir, about] of packages) {
  const sf = program.getSourceFile(join(root, dir, 'src/index.ts'));
  const mod = checker.getSymbolAtLocation(sf);
  const exports = checker.getExportsOfModule(mod).sort((a, b) => a.name.localeCompare(b.name));
  out += `\n## ${name}\n\n${about}. ${exports.length} exports.\n\n| Export | Kind | Source | Summary |\n|---|---|---|---|\n`;
  for (const ex of exports) {
    const sym = ex.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(ex) : ex;
    const decl = sym.declarations?.[0];
    const file = decl ? relative(root, decl.getSourceFile().fileName).split(sep).join('/') : '';
    out += `| \`${ex.name}\` | ${kindOf(decl)} | ${file ? `[${file.replace(/^packages\//, '')}](../${file})` : ''} | ${summary(sym)} |\n`;
    total++;
  }
}

const target = join(root, 'docs/api.md');
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== out) {
    console.log('FAIL docs/api.md is out of date: run node scripts/api-index.mjs');
    process.exit(1);
  }
  console.log(`API reference up to date: ${total} exports in ${packages.length} packages.`);
} else {
  writeFileSync(target, out);
  console.log(`Wrote docs/api.md: ${total} exports in ${packages.length} packages.`);
}
